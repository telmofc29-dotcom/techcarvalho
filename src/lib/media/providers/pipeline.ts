/**
 * The legacy four-value status, kept because the engine job, the admin surfaces
 * and the requirement notes all read it.
 *
 * It is now DERIVED from `PipelineReport.outcome` (see `legacyStatusFor`)
 * rather than computed independently, so the coarse and the precise answer
 * cannot drift apart. The seven-state taxonomy in outcome.ts is the real one:
 * this collapses `WRONG_ENTITY_RESULTS` / `RIGHTS_UNCERTAIN` /
 * `PROVENANCE_INCOMPLETE` into one bucket, and that collapse is exactly what
 * made the `|other versions=` parser bug invisible.
 */
export type PipelineStatus =
  /** Ran to completion, at least one candidate accepted. */
  | "resolved"
  /** Ran to completion, nothing acceptable found. A LEGITIMATE result. */
  | "no_acceptable_candidate"
  /** Ran to completion, the provider genuinely had nothing. Also legitimate. */
  | "no_results"
  /** Could not run properly. NOT the same as finding nothing. */
  | "provider_unavailable";

export type PipelineReport = {
  identity: SubjectIdentity;
  status: PipelineStatus;
  /**
   * Which of the seven outcome states this search ended in, and the positive
   * evidence for that state. Read this in preference to `status`.
   */
  outcome: SearchOutcome;
  /** Every query issued, and what it returned. */
  queryLog: { query: ProviderQuery; hits: number; note: string }[];
  /** Expansions generated and refused before any request was made. */
  refusedQueries: { value: string; strategy: string; reason: string }[];
  evaluations: CandidateEvaluation[];
  ranking: RankingResult | null;
  /** The row that would be written for the winner, if any. */
  proposedRow: ProposedAssetRow | null;
  publicationSafety: PublicationSafety | null;
  /** Prose an editor can read. */
  narrative: string;
};

export type PipelineOptions = {
  maxCandidates: number;
  ranking: RankingContext;
  /** Alt text for the proposed row; the engine does not invent descriptions. */
  altTextFor?: (identity: SubjectIdentity, provenance: ProvenanceRecord) => string | null;
  /** Storage path for the proposed row; supplied by the caller that will write it. */
  storagePathFor?: (identity: SubjectIdentity, provenance: ProvenanceRecord) => string;
};

/**
 * Run the full pipeline for one subject across one or more providers.
 *
 * Note the provider list is a parameter. There is no import of any specific
 * provider in this file, and no branch anywhere that special-cases one — the
 * engine is not built around Wikimedia Commons, Commons is simply the first
 * source that passed approval.
 */
export async function runAcquisitionPipeline(
  identity: SubjectIdentity,
  providers: MediaProvider[],
  options: PipelineOptions
): Promise<PipelineReport> {
  const queryLog: PipelineReport["queryLog"] = [];
  const refusedQueries: PipelineReport["refusedQueries"] = [];
  const evaluations: CandidateEvaluation[] = [];
  /**
   * What each provider did, recorded as it happens.
   *
   * This is what makes NO_RESULTS provable rather than assumed: the classifier
   * is not handed "there are no candidates" and left to infer why, it is handed
   * each provider's own answer plus what that provider can attest about the
   * responses behind it.
   */
  const episodes: ProviderEpisode[] = [];

  const plan = expandQueries(identity);
  refusedQueries.push(...plan.rejected.map((r) => ({ value: r.value, strategy: r.strategy as string, reason: r.reason })));

  for (const provider of providers) {
    if (!provider.approval.approvedForSearch) {
      queryLog.push({
        query: { strategy: "text_search", value: "(none issued)", rationale: "", identityTokens: [] },
        hits: 0,
        note: `${provider.approval.label} is NOT approved for search: ${provider.approval.rationale}`,
      });
      episodes.push({
        approval: provider.approval,
        searched: false,
        // No request was issued, so there is no answer to record. `searched`
        // is what the classifier reads; this status is never inspected for an
        // unsearched provider, and an unsearched source is never an empty one.
        outcome: { status: "outage", detail: "not approved for search — no request was issued" },
        attestation: null,
        candidates: 0,
      });
      continue;
    }

    const search = await provider.search([...plan.strict, ...plan.broad], { maxCandidates: options.maxCandidates });
    queryLog.push(...search.queryLog);
    episodes.push({
      approval: provider.approval,
      searched: true,
      outcome: search.outcome,
      attestation: search.attestation ?? null,
      candidates: search.candidates.length,
    });

    if (search.outcome.status !== "ok" && search.outcome.status !== "no_results") {
      // A provider failure must never look like "found nothing".
      evaluations.push({
        key: `${provider.approval.id}::provider`,
        descriptor: { title: `(${provider.approval.label} unavailable)`, fileName: null, categories: [], descriptionText: null, mimeType: null },
        provider: provider.approval,
        stageReached: "entity",
        accepted: false,
        rejection: {
          code: search.outcome.status === "malformed" ? "provider_malformed" : "provider_outage",
          message:
            `${provider.approval.label} could not be searched (${search.outcome.status}: ` +
            `${"detail" in search.outcome ? search.outcome.detail : ""}). This is NOT a finding of "no photograph exists" — ` +
            "the search did not happen. Recorded distinctly so a broken source never masquerades as an empty one.",
        },
        entityMatch: null, provenance: null, rights: null,
      });
      continue;
    }

    for (const candidate of search.candidates) {
      const descriptor = descriptorOf(candidate);
      // Cheap gate first: do not spend a network round-trip resolving the
      // provenance of a file that is plainly the wrong product.
      const preMatch = assessEntityMatch(identity, descriptor);
      if (preMatch.verdict !== "confirmed") {
        evaluations.push({
          key: `${provider.approval.id}::${candidate.providerRef}`,
          descriptor, provider: provider.approval,
          stageReached: "entity", accepted: false,
          rejection: {
            code: preMatch.verdict === "ambiguous" ? "entity_ambiguous" : "entity_mismatch",
            message: preMatch.reason,
          },
          entityMatch: preMatch, provenance: null, rights: null,
        });
        continue;
      }

      const resolved = await provider.resolve(candidate);
      evaluations.push(
        evaluateCandidate({
          identity,
          descriptor: resolved.provenance ? enrichDescriptor(descriptor, resolved.provenance) : descriptor,
          provenance: resolved.provenance,
          resolveOutcome: resolved.outcome,
          provider: provider.approval,
          key: `${provider.approval.id}::${candidate.providerRef}`,
        })
      );
    }
  }

  const reconciled = reconcileDuplicates(evaluations);
  const accepted = reconciled.filter((e) => e.accepted && e.provenance && e.rights && e.entityMatch);

  const rankable: RankableCandidate[] = accepted.map((e) => ({
    key: e.key,
    descriptor: e.descriptor,
    provenance: e.provenance!,
    entityMatch: e.entityMatch!,
    rights: e.rights!,
    approval: e.provider,
  }));

  const ranking = rankable.length > 0 ? rankCandidates(rankable, options.ranking) : null;

  let proposedRow: ProposedAssetRow | null = null;
  let publicationSafety: PublicationSafety | null = null;
  if (ranking?.winner) {
    const p = ranking.winner.candidate.provenance;
    proposedRow = buildProposedRow({
      storagePath: options.storagePathFor?.(identity, p) ?? `image/pending-${p.contentHash ?? "unhashed"}`,
      altText: options.altTextFor?.(identity, p) ?? null,
      provenance: p,
    });
    publicationSafety = validateEnginePublicationSafety(proposedRow);
  }

  // The single classification point. There is no other place in this function
  // where an outcome is decided, and no branch that falls through to "found
  // nothing" — `classifySearchOutcome` either establishes a state positively or
  // returns PROVIDER_PARSE_FAILURE.
  const outcome = classifySearchOutcome({ episodes, evaluations: reconciled });
  const status: PipelineStatus = legacyStatusFor(outcome.state);

  return {
    identity,
    status,
    outcome,
    queryLog,
    refusedQueries,
    evaluations: reconciled,
    ranking,
    proposedRow,
    publicationSafety,
    narrative: buildNarrative(identity, status, outcome, reconciled, ranking),
  };
}

function descriptorOf(c: DiscoveredCandidate): CandidateDescriptor {
  return {
    title: c.title,
    fileName: c.providerRef.replace(/^File:/i, "") || null,
    categories: c.descriptors.filter((d) => /^Category:/i.test(d)),
    descriptionText: c.descriptors.filter((d) => !/^Category:/i.test(d)).join(" ") || null,
    mimeType: null,
  };
}

/**
 * Fold what resolution learned back into the descriptor before the full
 * evaluation re-runs entity matching.
 *
 * The EXIF camera model is the addition that matters: it is only available
 * after resolution, and it is what catches a photograph taken BY the subject
 * camera whose title happens not to say so.
 */
function enrichDescriptor(d: CandidateDescriptor, p: ProvenanceRecord): CandidateDescriptor {
  const exifModel = p.evidence
    .map((e) => /^EXIF Model="(.*)"$/.exec(e.detail)?.[1])
    .find((v): v is string => Boolean(v));
  return {
    ...d,
    mimeType: p.mimeType ?? d.mimeType,
    fileName: p.originalFileName ?? d.fileName,
    exifCameraModel: exifModel ?? d.exifCameraModel ?? null,
  };
}

function buildNarrative(
  identity: SubjectIdentity,
  status: PipelineStatus,
  outcome: SearchOutcome,
  evaluations: CandidateEvaluation[],
  ranking: RankingResult | null
): string {
  // The state and its justification lead, because the coarse status below is
  // the thing that once read identically for "nothing exists" and "our parser
  // is broken".
  const head =
    `OUTCOME ${outcome.state} — ${OUTCOME_MEANINGS[outcome.state]}\n` +
    outcome.because.map((b) => `  · ${b}`).join("\n");

  return `${head}\n${legacyNarrative(identity, status, evaluations, ranking)}`;
}

function legacyNarrative(
  identity: SubjectIdentity,
  status: PipelineStatus,
  evaluations: CandidateEvaluation[],
  ranking: RankingResult | null
): string {
  const byCode = new Map<string, number>();
  for (const e of evaluations) {
    if (e.rejection) byCode.set(e.rejection.code, (byCode.get(e.rejection.code) ?? 0) + 1);
  }
  const breakdown = [...byCode.entries()].map(([c, n]) => `${c}×${n}`).join(", ") || "none";

  switch (status) {
    case "resolved":
      return (
        `${identity.canonicalName}: ${evaluations.length} candidate(s) examined, ${evaluations.filter((e) => e.accepted).length} cleared every gate. ` +
        `Rejections: ${breakdown}. ${ranking?.whyItWon ?? ""}`
      );
    case "no_acceptable_candidate":
      return (
        `${identity.canonicalName}: candidates WERE found and every one was rejected (${breakdown}). ` +
        "This is a finding, not a gap — the search worked and the material is unsuitable. Do not stretch to fill a quota."
      );
    case "no_results":
      return (
        `${identity.canonicalName}: every query ran successfully and returned nothing. No usable photograph appears to exist ` +
        "at the searched providers yet. Blocked on photography, not on permission; worth a scheduled recheck rather than a negotiation."
      );
    case "provider_unavailable":
      return (
        `${identity.canonicalName}: the search DID NOT COMPLETE (${breakdown}). This must not be recorded as "nothing found" — ` +
        "the 2026-08 lesson in CLAUDE.md is that a failure indistinguishable from an empty result hides for weeks."
      );
  }
}
