// Synthetic imagery — the rule that has nothing to do with rights
// ---------------------------------------------------------------------------

/**
 * Phrases that mean the image was generated rather than photographed.
 *
 * Commons hosts a growing volume of AI imagery under impeccable CC0 tags. A
 * CC0 "photograph" of a PS5 Pro generated by a diffusion model is perfectly
 * licensed and completely false, and it is the single most dangerous candidate
 * class this pipeline can encounter — the licence check passes, the entity
 * check passes (the model drew the right-looking object), and the result is a
 * fabricated depiction of a real product on a page that implies documentation.
 *
 * docs/product-media-strategy.md rule 2: "Never a generated image presented
 * as, or mistakable for, a photograph of a real product." This enforces it
 * before acquisition rather than hoping someone notices later.
 */
const SYNTHETIC_MARKERS: [RegExp, string][] = [
  [/\bai[\s-]?generated\b/i, "described as AI-generated"],
  [/\bgenerated (?:by|with|using) (?:ai|an ai|a neural)/i, "described as generated by AI"],
  [/\bstable diffusion\b/i, "names Stable Diffusion"],
  [/\bmidjourney\b/i, "names Midjourney"],
  [/\bdall[\s·.-]?e\b/i, "names DALL-E"],
  [/\bflux\.1\b/i, "names FLUX.1"],
  [/\bimagen\b/i, "names Imagen"],
  [/\bgemini (?:image|nano banana)\b/i, "names a Gemini image model"],
  [/\bfirefly\b/i, "names Adobe Firefly"],
  [/\btext[\s-]?to[\s-]?image\b/i, "described as text-to-image output"],
  [/\bsynthetic (?:image|photo|photograph)\b/i, "described as a synthetic image"],
  [/\bcategory:ai[\s-]?generated/i, "member of an AI-generated category"],
  [/\bcategory:images generated by/i, "member of a generated-images category"],
];

export type SyntheticVerdict = { synthetic: boolean; marker: string | null; detail: string };

/**
 * Does anything at source indicate this image was generated?
 *
 * Fails closed on the marker, not on a judgement of how real it looks. There
 * is no reliable way to tell a good generated product render from a photograph
 * by inspection, so the only defensible rule is: if the source says or hints
 * it was generated, it is out — regardless of how good the licence is.
 */
export function detectSyntheticImagery(
  descriptor: CandidateDescriptor,
  provenance: ProvenanceRecord | null
): SyntheticVerdict {
  const hay = [
    descriptor.title,
    descriptor.fileName ?? "",
    descriptor.descriptionText ?? "",
    ...descriptor.categories,
    ...(provenance?.evidence.map((e) => e.detail) ?? []),
    provenance?.creator ?? "",
  ].join(" \n ");

  for (const [pattern, why] of SYNTHETIC_MARKERS) {
    if (pattern.test(hay)) {
      return {
        synthetic: true,
        marker: why,
        detail:
          `Source metadata ${why}. A generated image of a real product is a fabricated depiction however good its ` +
          "licence is, and this site never publishes one as, or mistakable for, product photography.",
      };
    }
  }
  return { synthetic: false, marker: null, detail: "Nothing at source indicates the image was generated." };
}

/**
 * Minimum long edge for an image the engine will archive as a product photo.
 *
 * Not a rights rule and not arbitrary: below this a hero visibly softens on a
 * 2x display, and an upscaled small image looks like something taken without
 * permission even when it was not. A candidate under the floor is reported as
 * a finding rather than acquired, so the requirement stays open and honest
 * instead of being closed with something unusable.
 */
export const MIN_ACQUIRE_LONG_EDGE = 800;

/**
 * File types that can be a product PHOTOGRAPH.
 *
 * The first live run made the case for this gate better than any argument
 * would have: searching for the Intel Core Ultra 9 285K accepted three
 * candidates, and all three were **`.stl` files** — 3D-printable models of the
 * processor. Correct product, CC0, high entity confidence, and not a
 * photograph in any sense. Commons is a media repository, not an image
 * library: it holds STL meshes, PDFs, SVGs, OGV video and MIDI, and every one
 * of them can carry an impeccable licence.
 *
 * SVG is excluded deliberately rather than by oversight. A vector file naming
 * a product is a logo — the "Galaxy S26 Ultra" hit in the earlier audit was a
 * Samsung logo SVG — and a logo is never a photograph of a device.
 */
const ACQUIRABLE_MIME_TYPES = new Set(["image/jpeg", "image/png", "image/webp"]);

export type CandidateEvaluation = {
  key: string;
  descriptor: CandidateDescriptor;
  provider: ProviderApproval;
  /** The last stage this candidate reached. */
  stageReached: "entity" | "provenance" | "rights" | "duplicate" | "ranking";
  accepted: boolean;
  rejection: { code: RejectionCode; message: string } | null;
  entityMatch: EntityMatchAssessment | null;
  provenance: ProvenanceRecord | null;
  rights: RightsAssessment | null;
};

/**
 * Stages 2-4 for one candidate. Pure — the provenance was already fetched.
 *
 * Entity matching runs FIRST, before rights are even looked at. Verifying the
 * licence of a photograph of the wrong product is wasted work at best, and at
 * worst it produces a beautifully documented wrong answer.
 */
export function evaluateCandidate(input: {
  identity: SubjectIdentity;
  descriptor: CandidateDescriptor;
  provenance: ProvenanceRecord | null;
  /** Non-ok means resolution failed; that is a rejection, never a pass. */
  resolveOutcome: ProviderOutcome;
  provider: ProviderApproval;
  key: string;
}): CandidateEvaluation {
  const base = {
    key: input.key,
    descriptor: input.descriptor,
    provider: input.provider,
    entityMatch: null as EntityMatchAssessment | null,
    provenance: null as ProvenanceRecord | null,
    rights: null as RightsAssessment | null,
  };

  // --- Stage 2: entity validation -----------------------------------------
  const entityMatch = assessEntityMatch(input.identity, input.descriptor);
  base.entityMatch = entityMatch;

  if (entityMatch.verdict === "rejected") {
    return {
      ...base, stageReached: "entity", accepted: false,
      rejection: { code: "entity_mismatch", message: entityMatch.reason },
    };
  }
  if (entityMatch.verdict === "ambiguous") {
    return {
      ...base, stageReached: "entity", accepted: false,
      rejection: { code: "entity_ambiguous", message: entityMatch.reason },
    };
  }

  // --- Stage 3: provenance resolution --------------------------------------
  if (input.resolveOutcome.status !== "ok" || !input.provenance) {
    const detail =
      input.resolveOutcome.status === "ok"
        ? "resolution reported success but returned no provenance record"
        : `${input.resolveOutcome.status}: ${"detail" in input.resolveOutcome ? input.resolveOutcome.detail : ""}`;
    const code: RejectionCode =
      input.resolveOutcome.status === "outage" || input.resolveOutcome.status === "rate_limited"
        ? "provider_outage"
        : input.resolveOutcome.status === "malformed"
          ? "provider_malformed"
          : "provenance_unresolvable";
    return {
      ...base, stageReached: "provenance", accepted: false,
      rejection: {
        code,
        message:
          `Could not resolve this candidate's own source page (${detail}). A candidate whose provenance could not ` +
          "be read is not a candidate — an unavailable check is a stop, never a skip.",
      },
    };
  }
  base.provenance = input.provenance;

  // --- Stage 4: rights verification ----------------------------------------
  const rights = verifyRights(input.provenance);
  base.rights = rights;

  if (rights.evidenceClass === "restricted") {
    return {
      ...base, stageReached: "rights", accepted: false,
      rejection: { code: "rights_restricted", message: rights.narrative },
    };
  }
  if (rights.evidenceClass === "evidence_conflicting") {
    return {
      ...base, stageReached: "rights", accepted: false,
      rejection: { code: "rights_conflicting", message: rights.narrative },
    };
  }
  if (rights.evidenceClass === "evidence_incomplete") {
    return {
      ...base, stageReached: "rights", accepted: false,
      rejection: { code: "rights_incomplete", message: rights.narrative },
    };
  }

  // --- Stage 3b: is it even a photograph-shaped file? ----------------------
  const mime = (input.provenance.mimeType ?? "").toLowerCase();
  if (!ACQUIRABLE_MIME_TYPES.has(mime)) {
    return {
      ...base, stageReached: "provenance", accepted: false,
      rejection: {
        code: "unsupported_media_type",
        message:
          `Media type "${mime || "unknown"}" cannot be a product photograph. Acquirable types are ` +
          `${[...ACQUIRABLE_MIME_TYPES].join(", ")}. A correctly-licensed 3D model, PDF, vector logo or video of the ` +
          "right product is still not a photograph of it.",
      },
    };
  }

  // --- Stage 4b: synthetic imagery -----------------------------------------
  // Deliberately AFTER rights, so the log shows a generated image was refused
  // on its own merits rather than being lumped in with a licence failure.
  const synthetic = detectSyntheticImagery(input.descriptor, input.provenance);
  if (synthetic.synthetic) {
    return {
      ...base, stageReached: "rights", accepted: false,
      rejection: { code: "synthetic_imagery", message: synthetic.detail },
    };
  }

  // --- Stage 4c: quality floor ---------------------------------------------
  const longEdge = Math.max(input.provenance.width ?? 0, input.provenance.height ?? 0);
  if (longEdge < MIN_ACQUIRE_LONG_EDGE) {
    return {
      ...base, stageReached: "rights", accepted: false,
      rejection: {
        code: "quality_below_floor",
        message:
          `Long edge ${longEdge || "unknown"}px is below the ${MIN_ACQUIRE_LONG_EDGE}px floor for an archived product ` +
          "photograph. The licence is fine; the picture is not usable. Recording this as a finding keeps the " +
          "requirement honestly open instead of closing it with something that will have to be replaced.",
      },
    };
  }

  return { ...base, stageReached: "rights", accepted: true, rejection: null };
}

// ---------------------------------------------------------------------------
// Stage 5: duplicate reconciliation across providers
// ---------------------------------------------------------------------------

/**
 * Collapse candidates that are the SAME FILE reached through different
 * providers, and refuse the whole group when they disagree about its licence.
 *
 * The disagreement case is the important one and it fails closed for both
 * copies. If provider A says CC BY 4.0 and provider B says CC BY-NC for
 * byte-identical content, one of them is wrong about the terms we would be
 * relying on. Picking the friendlier reading is how a NonCommercial photograph
 * ends up on a commercial page; picking the stricter one silently discards a
 * possibly-fine asset while leaving the underlying contradiction unexamined.
 * Blocking both and saying so is the only honest outcome.
 */
export function reconcileDuplicates(evaluations: CandidateEvaluation[]): CandidateEvaluation[] {
  const groups = new Map<string, CandidateEvaluation[]>();
  const ungrouped: CandidateEvaluation[] = [];

  for (const e of evaluations) {
    const hash = e.provenance?.contentHash;
    if (!e.accepted || !hash) {
      ungrouped.push(e);
      continue;
    }
    const list = groups.get(hash) ?? [];
    list.push(e);
    groups.set(hash, list);
  }

  const out: CandidateEvaluation[] = [...ungrouped];

  for (const [hash, group] of groups) {
    if (group.length === 1) {
      out.push(group[0]);
      continue;
    }

    // Same bytes, different licence claims?
    const licences = group.map((g) => g.provenance!.licenceDeclared ?? g.provenance!.licenceMetadata);
    const allAgree = licences.every((l) => licencesAgree(l, licences[0]));
    if (!allAgree) {
      const summary = group
        .map((g) => `${g.provider.label} says "${g.provenance!.licenceDeclared ?? g.provenance!.licenceMetadata}"`)
        .join("; ");
      for (const g of group) {
        out.push({
          ...g,
          stageReached: "duplicate",
          accepted: false,
          rejection: {
            code: "duplicate_licence_conflict",
            message:
              `Byte-identical content (sha256 ${hash.slice(0, 12)}…) carries CONFLICTING licence metadata across providers: ${summary}. ` +
              "One of these is wrong about the terms we would be relying on. Both copies are refused — the safe-looking " +
              "reading is not evidence, and quietly taking the stricter one would hide the contradiction instead of surfacing it.",
          },
        });
      }
      continue;
    }

    // Agreeing duplicates: keep the copy with the most primary evidence,
    // preferring a provider that exposes primary evidence at all.
    const sorted = [...group].sort((a, b) => {
      const ap = a.provider.exposesPrimaryEvidence ? 1 : 0;
      const bp = b.provider.exposesPrimaryEvidence ? 1 : 0;
      if (ap !== bp) return bp - ap;
      return (b.provenance!.evidence.length) - (a.provenance!.evidence.length);
    });
    out.push(sorted[0]);
    for (const loser of sorted.slice(1)) {
      out.push({
        ...loser,
        stageReached: "duplicate",
        accepted: false,
        rejection: {
          code: "duplicate_of_better",
          message:
            `Same file (sha256 ${hash.slice(0, 12)}…) as the copy from ${sorted[0].provider.label}, which agrees on the licence ` +
            `and carries more primary evidence (${sorted[0].provenance!.evidence.length} items vs ${loser.provenance!.evidence.length}). ` +
            "Deduplicated in favour of the better-evidenced copy.",
        },
      });
    }
  }

  return out;
}

