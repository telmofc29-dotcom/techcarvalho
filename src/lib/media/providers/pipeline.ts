/** The exact `media_assets` row shape the pipeline proposes to write. */
export type ProposedAssetRow = {
  storage_path: string;
  media_type: "image";
  alt_text: string | null;
  width: number | null;
  height: number | null;
  license: string | null;
  creator: string | null;
  source_type: "public_domain_or_cc";
  asset_role: "product_photo";
  source_url: string | null;
  attribution: string | null;
  attribution_required: boolean;
  ai_generated: false;
  owned: false;
  rights_status: typeof ENGINE_MAX_RIGHTS_STATUS;
  publication_status: "private";
};

export type PublicationSafety = {
  /** True when the proposed row is correctly REFUSED by the publication gate. */
  safe: boolean;
  publishEligibility: ReturnType<typeof evaluatePublishEligibility>;
  provenanceVerdict: ReturnType<typeof evaluateProvenance>;
  explanation: string;
};

/**
 * Assert that what the engine is about to write cannot publish itself.
 *
 * This is an invariant check, not a permission check — `safe: true` means
 * "correctly blocked". A `safe: false` here is a defect in this pipeline, and
 * the caller must abort rather than proceed.
 */
export function validateEnginePublicationSafety(row: ProposedAssetRow): PublicationSafety {
  const asset: ProvenanceAsset = {
    source_type: row.source_type,
    rights_status: row.rights_status,
    license: row.license,
    creator: row.creator,
    attribution: row.attribution,
    attribution_required: row.attribution_required,
    source_url: row.source_url,
    owned: row.owned,
    ai_generated: row.ai_generated,
  };

  const publishEligibility = evaluatePublishEligibility({
    rights_status: row.rights_status,
    owned: row.owned,
    source_type: row.source_type,
  });
  const provenanceVerdict = evaluateProvenance(asset);

  const safe = !publishEligibility.allowed && !provenanceVerdict.publishable;

  return {
    safe,
    publishEligibility,
    provenanceVerdict,
    explanation: safe
      ? `The proposed row carries rights_status='${row.rights_status}', owned=false and source_type='${row.source_type}'. ` +
        `evaluatePublishEligibility() refuses it and evaluateProvenance() classifies it '${provenanceVerdict.rightsClass}' ` +
        `with ${provenanceVerdict.findings.filter((f) => f.severity === "blocker").length} blocker(s). The engine has therefore ` +
        "produced an archived, credited, unpublishable record — which is exactly the intended output. A human moves it further."
      : "INVARIANT VIOLATED: the row the engine proposes to write would clear the publication gate on its own. " +
        "The engine must never be able to publish. Abort rather than write this row.",
  };
}

/** Build the row the pipeline would write for an accepted candidate. */
export function buildProposedRow(input: {
  storagePath: string;
  altText: string | null;
  provenance: ProvenanceRecord;
}): ProposedAssetRow {
  const p = input.provenance;
  return {
    storage_path: input.storagePath,
    media_type: "image",
    alt_text: input.altText,
    width: p.width,
    height: p.height,
    license: p.licenceDeclared ?? p.licenceMetadata,
    creator: p.creator,
    source_type: "public_domain_or_cc",
    asset_role: "product_photo",
    source_url: p.sourcePageUrl,
    attribution: p.attributionText,
    attribution_required: p.attributionRequired ?? true,
    ai_generated: false,
    owned: false,
    rights_status: ENGINE_MAX_RIGHTS_STATUS,
    publication_status: "private",
  };
}

