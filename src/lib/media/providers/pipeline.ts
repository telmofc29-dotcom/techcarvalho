// The ONE central media pipeline. Every provider feeds this; nothing bypasses it.
//
// STAGES, IN ORDER, EACH ABLE TO STOP THE CANDIDATE DEAD
// ------------------------------------------------------
//   1. discovery            provider returns rights-free hits
//   2. entity validation    is this a picture of THAT product? ambiguous = stop
//   3. provenance           resolve the item's own source page for primary evidence
//   4. rights verification  what the evidence supports; conflict = stop
//   5. duplicate reconciliation  the same file from two providers, and the case
//                           where the two disagree about its licence
//   6. quality / ranking     choose among the survivors, and record why
//   7. publication validation  prove the proposed row does NOT clear the
//                           publication gate, because the engine must never
//                           produce something that does
//
// WHY STAGE 7 EXISTS WHEN THE ENGINE NEVER PUBLISHES
// ---------------------------------------------------
// Because "the engine never publishes" is a property of today's code, and this
// makes it a property that is CHECKED. `validateEnginePublicationSafety()`
// takes the exact row the pipeline would write and asserts that
// evaluatePublishEligibility() refuses it. If a future change made engine
// output publishable, that assertion fails in the unit tests rather than on
// the live site.
//
// FAIL-CLOSED IS THE DEFAULT RETURN, NOT AN EXCEPTION PATH
// --------------------------------------------------------
// Every early return in this file is a refusal. There is no branch that
// accepts a candidate for lack of a reason to reject it.
//
// Pure except `runAcquisitionPipeline`, which drives providers over the network.

